function metrics = hmfc_run_metrics(run,plant,controller)
%HMFC_RUN_METRICS Public metrics shared by every numerical controller.
trueAngle = atan2(-plant.n(1),plant.n(2));
metrics = struct('finalError',run.error(end),'finalForce',run.force(end), ...
    'minForce',min(run.force),'maxForceError',max(abs(run.force-controller.fd)), ...
    'tailRmsError',sqrt(mean(run.error(run.t>=run.t(end)-2).^2)), ...
    'finalTangentialVelocity',run.state(end,2), ...
    'finalAngleError',run.angle(end)-trueAngle, ...
    'peakTorque',max(abs(run.tau),[],'all'), ...
    'operatingRegionSatisfied',run.operatingRegionSatisfied, ...
    'firstRegionExitTime',run.firstRegionExitTime);
end
