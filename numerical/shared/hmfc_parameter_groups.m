function [robot,plant,controller,task] = hmfc_parameter_groups()
%HMFC_PARAMETER_GROUPS Separate physical, controller and reference defaults.
common = hmfc_parameters();
robot = struct('l1',common.l1,'l2',common.l2,'m1',common.m1,'m2',common.m2, ...
    'lc1',common.lc1,'lc2',common.lc2,'I1',common.I1,'I2',common.I2,'g',common.g);
plant = struct('p0',common.p0,'n',common.n,'T',common.T, ...
    'xMin',common.xMin,'xMax',common.xMax,'q2Min',common.q2Min, ...
    'q2Max',common.q2Max,'minSinQ2',common.minSinQ2,'q0',common.q0, ...
    'enforceOperatingRegion',true);
controller = struct('kp',common.kp,'kv',common.kv,'fd',common.fd);
task = struct('origin',common.p0,'axis',common.T,'targetX',common.targetX, ...
    'setpoint',common.setpoint);
end
